-- -----------------------------------------------------------------------------
-- 1. LIMPEZA PREVENTIVA DAS TABELAS (ORDEM INVERSA DE DEPENDÊNCIA REFERENCIAL)
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS desempenho_diario;
DROP TABLE IF EXISTS resumo_funil;
DROP TABLE IF EXISTS email_marketing;
DROP TABLE IF EXISTS landing_page;
DROP TABLE IF EXISTS anuncio;
DROP TABLE IF EXISTS publico_alvo;
DROP TABLE IF EXISTS campanha;
DROP TABLE IF EXISTS conta;
DROP TABLE IF EXISTS usuario;

-- -----------------------------------------------------------------------------
-- 2. TABELA: usuario (Autenticação e RBAC - Requisito RF06)
-- -----------------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    perfil VARCHAR(30) NOT NULL,
    CONSTRAINT chk_usuario_perfil CHECK (perfil IN ('ADMIN', 'GESTOR_MARKETING', 'ANALISTA'))
);

-- -----------------------------------------------------------------------------
-- 3. TABELA: conta (Cliente Anunciante com Value Object Localizacao embutido)
-- -----------------------------------------------------------------------------
CREATE TABLE conta (
    id_conta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_conta VARCHAR(120) NOT NULL,
    segmento VARCHAR(80) NOT NULL,
    produto_principal VARCHAR(100) NOT NULL,
    porte_empresa VARCHAR(50) NOT NULL,
    ano_inicio_cliente INT NOT NULL,
    status_conta VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    cidade VARCHAR(100) NOT NULL,
    estado CHAR(2) NOT NULL,
    regiao VARCHAR(40) NOT NULL,
    CONSTRAINT chk_conta_status CHECK (status_conta IN ('ATIVO', 'INATIVO')),
    CONSTRAINT chk_conta_ano CHECK (ano_inicio_cliente >= 2000)
);

-- -----------------------------------------------------------------------------
-- 4. TABELA: publico_alvo (Segmentação de Audiência com Localizacao embutida)
-- -----------------------------------------------------------------------------
CREATE TABLE publico_alvo (
    id_publico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_publico VARCHAR(120) NOT NULL,
    faixa_etaria VARCHAR(20) NOT NULL,
    genero VARCHAR(30) NOT NULL,
    tipo_segmentacao VARCHAR(80) NOT NULL,
    intencao_compra VARCHAR(30) NOT NULL,
    tamanho_estimado_publico BIGINT NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    estado CHAR(2) NOT NULL,
    regiao VARCHAR(40) NOT NULL,
    CONSTRAINT chk_publico_tamanho CHECK (tamanho_estimado_publico > 0)
);

-- -----------------------------------------------------------------------------
-- 5. TABELA: campanha (Entidade Central de Domínio - Requisitos RF01 e RF05)
-- -----------------------------------------------------------------------------
CREATE TABLE campanha (
    id_campanha BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conta BIGINT NOT NULL,
    nome_campanha VARCHAR(150) NOT NULL,
    canal VARCHAR(60) NOT NULL,
    objetivo VARCHAR(80) NOT NULL,
    segmento VARCHAR(80) NOT NULL,
    produto VARCHAR(100) NOT NULL,
    status_campanha VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    posicao_funil VARCHAR(50) NOT NULL,
    abrangencia_geografica VARCHAR(60) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    orcamento_planejado DECIMAL(15, 2) NOT NULL,
    CONSTRAINT fk_campanha_conta FOREIGN KEY (id_conta) REFERENCES conta(id_conta) ON DELETE RESTRICT,
    CONSTRAINT chk_campanha_status CHECK (status_campanha IN ('ATIVO', 'PAUSADO', 'ENCERRADO', 'INATIVO', 'ARQUIVADO')),
    CONSTRAINT chk_campanha_datas CHECK (data_fim >= data_inicio),
    CONSTRAINT chk_campanha_orcamento CHECK (orcamento_planejado >= 0)
);

-- -----------------------------------------------------------------------------
-- 6. TABELA: anuncio (Peça Criativa e Versão de Teste A/B)
-- -----------------------------------------------------------------------------
CREATE TABLE anuncio (
    id_anuncio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campanha BIGINT NOT NULL,
    nome_anuncio VARCHAR(150) NOT NULL,
    formato VARCHAR(60) NOT NULL,
    versao_teste_ab VARCHAR(5) NOT NULL,
    linha_criativa VARCHAR(80) NOT NULL,
    status_anuncio VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    nota_qualidade_criativo DECIMAL(4, 2) NOT NULL,
    CONSTRAINT fk_anuncio_campanha FOREIGN KEY (id_campanha) REFERENCES campanha(id_campanha) ON DELETE CASCADE,
    CONSTRAINT chk_anuncio_status CHECK (status_anuncio IN ('ATIVO', 'PAUSADO', 'ENCERRADO', 'INATIVO', 'ARQUIVADO')),
    CONSTRAINT chk_anuncio_nota CHECK (nota_qualidade_criativo BETWEEN 0.0 AND 10.0)
);

-- -----------------------------------------------------------------------------
-- 7. TABELA: landing_page (Página de Destino e Conversão)
-- -----------------------------------------------------------------------------
CREATE TABLE landing_page (
    id_landing_page BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campanha BIGINT NOT NULL,
    nome_landing_page VARCHAR(150) NOT NULL,
    tipo_pagina VARCHAR(80) NOT NULL,
    produto VARCHAR(100) NOT NULL,
    visitas BIGINT NOT NULL DEFAULT 0,
    conversoes BIGINT NOT NULL DEFAULT 0,
    tempo_medio_pagina_min DECIMAL(6, 2) NOT NULL DEFAULT 0,
    status_landing_page VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    CONSTRAINT fk_landing_page_campanha FOREIGN KEY (id_campanha) REFERENCES campanha(id_campanha) ON DELETE CASCADE,
    CONSTRAINT chk_landing_page_status CHECK (status_landing_page IN ('ATIVO', 'PAUSADO', 'ENCERRADO', 'INATIVO', 'ARQUIVADO')),
    CONSTRAINT chk_landing_page_visitas CHECK (visitas >= 0),
    CONSTRAINT chk_landing_page_conversoes CHECK (conversoes >= 0)
);

-- -----------------------------------------------------------------------------
-- 8. TABELA: email_marketing (Disparos de E-mail e Relacionamento)
-- -----------------------------------------------------------------------------
CREATE TABLE email_marketing (
    id_email BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conta BIGINT NOT NULL,
    tipo_email VARCHAR(80) NOT NULL,
    envios BIGINT NOT NULL DEFAULT 0,
    aberturas BIGINT NOT NULL DEFAULT 0,
    cliques BIGINT NOT NULL DEFAULT 0,
    conversoes BIGINT NOT NULL DEFAULT 0,
    descadastros BIGINT NOT NULL DEFAULT 0,
    data DATE NOT NULL,
    custo_envio DECIMAL(15, 2) NOT NULL DEFAULT 0,
    receita_atribuida DECIMAL(15, 2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_email_marketing_conta FOREIGN KEY (id_conta) REFERENCES conta(id_conta) ON DELETE RESTRICT,
    CONSTRAINT chk_email_envios CHECK (envios >= 0),
    CONSTRAINT chk_email_aberturas CHECK (aberturas >= 0),
    CONSTRAINT chk_email_custo CHECK (custo_envio >= 0),
    CONSTRAINT chk_email_receita CHECK (receita_atribuida >= 0)
);

-- -----------------------------------------------------------------------------
-- 9. TABELA: resumo_funil (Consolidação Mensal de Funil por Campanha)
-- -----------------------------------------------------------------------------
CREATE TABLE resumo_funil (
    id_funil BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_campanha BIGINT NOT NULL,
    data DATE NOT NULL,
    impressoes BIGINT NOT NULL DEFAULT 0,
    cliques BIGINT NOT NULL DEFAULT 0,
    leads BIGINT NOT NULL DEFAULT 0,
    oportunidades BIGINT NOT NULL DEFAULT 0,
    vendas BIGINT NOT NULL DEFAULT 0,
    custo DECIMAL(15, 2) NOT NULL DEFAULT 0,
    receita DECIMAL(15, 2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_resumo_funil_campanha FOREIGN KEY (id_campanha) REFERENCES campanha(id_campanha) ON DELETE CASCADE,
    CONSTRAINT chk_resumo_impressoes CHECK (impressoes >= 0),
    CONSTRAINT chk_resumo_cliques CHECK (cliques >= 0),
    CONSTRAINT chk_resumo_custo CHECK (custo >= 0),
    CONSTRAINT chk_resumo_receita CHECK (receita >= 0)
);

-- -----------------------------------------------------------------------------
-- 10. TABELA: desempenho_diario (Normalizada na 3FN - Desacoplada de Redundâncias)
-- -----------------------------------------------------------------------------
CREATE TABLE desempenho_diario (
    id_desempenho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_anuncio BIGINT NOT NULL,
    id_publico BIGINT NOT NULL,
    dispositivo VARCHAR(40) NOT NULL,
    data DATE NOT NULL,
    impressoes BIGINT NOT NULL DEFAULT 0,
    cliques BIGINT NOT NULL DEFAULT 0,
    leads BIGINT NOT NULL DEFAULT 0,
    oportunidades BIGINT NOT NULL DEFAULT 0,
    vendas BIGINT NOT NULL DEFAULT 0,
    custo DECIMAL(15, 2) NOT NULL DEFAULT 0,
    receita DECIMAL(15, 2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_desempenho_anuncio FOREIGN KEY (id_anuncio) REFERENCES anuncio(id_anuncio) ON DELETE CASCADE,
    CONSTRAINT fk_desempenho_publico FOREIGN KEY (id_publico) REFERENCES publico_alvo(id_publico) ON DELETE RESTRICT,
    CONSTRAINT chk_desempenho_impressoes CHECK (impressoes >= 0),
    CONSTRAINT chk_desempenho_cliques CHECK (cliques >= 0),
    CONSTRAINT chk_desempenho_custo CHECK (custo >= 0),
    CONSTRAINT chk_desempenho_receita CHECK (receita >= 0)
);

-- -----------------------------------------------------------------------------
-- 11. ÍNDICES DE PERFORMANCE PARA CHAVES ESTRANGEIRAS E FILTROS CRÍTICOS
-- -----------------------------------------------------------------------------
CREATE INDEX idx_campanha_conta ON campanha(id_conta);
CREATE INDEX idx_campanha_status ON campanha(status_campanha);
CREATE INDEX idx_anuncio_campanha ON anuncio(id_campanha);
CREATE INDEX idx_anuncio_status ON anuncio(status_anuncio);
CREATE INDEX idx_landing_page_campanha ON landing_page(id_campanha);
CREATE INDEX idx_email_marketing_conta ON email_marketing(id_conta);
CREATE INDEX idx_resumo_funil_campanha ON resumo_funil(id_campanha);
CREATE INDEX idx_desempenho_anuncio ON desempenho_diario(id_anuncio);
CREATE INDEX idx_desempenho_publico ON desempenho_diario(id_publico);
CREATE INDEX idx_desempenho_data ON desempenho_diario(data);
